# Program Menghitung Umur

print("=== PROGRAM HITUNG UMUR ===")

nama = input("Masukkan nama kamu: ")
tahun_lahir = int(input("Masukkan tahun lahir kamu: "))

tahun_sekarang = 2026
umur = tahun_sekarang - tahun_lahir

print("\n=== HASIL ===")
print("Halo", nama, "!")
print("Kamu lahir tahun", tahun_lahir, "dan sekarang berumur", umur, "tahun.")
