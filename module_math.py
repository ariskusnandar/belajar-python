# Program Menggunakan Module math

import math

print("=== MODULE MATH ===")

# Akar kuadrat
angka = 25
akar = math.sqrt(angka)
print(f"Akar kuadrat dari {angka} adalah {akar}")

# Nilai PI
print(f"Nilai PI: {math.pi}")

# Pembulatan ke atas dan ke bawah
angka = 3.7
print(f"Pembulatan ke atas dari {angka}: {math.ceil(angka)}")
print(f"Pembulatan ke bawah dari {angka}: {math.floor(angka)}")

# Faktorial
angka = 5
print(f"Faktorial dari {angka}: {math.factorial(angka)}")

# Pangkat
print(f"2 pangkat 5: {math.pow(2, 5)}")