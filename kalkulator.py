# Program Kalkulator Sederhana

# Meminta input angka dari user
angka1 = input("masukan angka pertama: ")
angka2 = input("masukan angka kedua: ")

# Mengubah input (string) menjadi integer (angka)
angka1 = int(angka1)
angka2 = int(angka2)

# Menghitung hasil penjumlahan
hasil = angka1 + angka2

# Menampilkan hasil
print(angka1, "+", angka2, "=", hasil)
