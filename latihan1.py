# Program Sapa Pengguna

print("=== PROGRAM SAPA PENGGUNA ===")

nama = input("Masukkan nama kamu: ")
tahun_lahir = int(input("Masukkan tahun lahir kamu: "))

tahun_sekarang = 2026
umur = tahun_sekarang - tahun_lahir

print (f"Halo {nama}, kamu lahir tahun {tahun_lahir}, dan sekarang umur {umur} tahun.")